function target = build_model(referenceFile)
root = fileparts(mfilename("fullpath"));
addpath(root);
if nargin < 1
    referenceFile = fullfile(root, "..", "results", "cca_contract", ...
        "cca_reference.csv");
end

config = simulation.nmpcSimulationConfig(simulation.nmpcConfig());
reference = read_reference(referenceFile, config.dt);
[ccaInput, ~] = pack_reference(reference, config);
initialState = reference(1, 2:7)';
assignin("base", "ccaInput", ccaInput);
assignin("base", "robot", robot_parameters());

model = "cca_nmpc_closed_loop";
target = fullfile(root, model + ".slx");
if bdIsLoaded(model)
    close_system(model, 0);
end
if isfile(target)
    delete(target);
end

new_system(model);
set_param(model, ...
    "SolverType", "Fixed-step", ...
    "Solver", "FixedStepDiscrete", ...
    "FixedStep", num2str(config.dt, 16), ...
    "StopTime", num2str(ccaInput(end, 1), 16), ...
    "SignalLogging", "on", ...
    "Location", [30, 30, 1900, 980]);

add_block("simulink/Sources/From Workspace", model + "/CCA local path", ...
    "VariableName", "ccaInput", ...
    "Interpolate", "on", ...
    "OutputAfterFinalValue", "Holding final value", ...
    "Position", [30, 180, 170, 220]);
add_chart(model + "/Current reference", [215, 180, 330, 220], [ ...
    "function output = select(value)", ...
    "output = value(1:6);", ...
    "end"]);
add_block("simulink/Math Operations/Sum", model + "/Tracking error", ...
    "Inputs", "+-", "Position", [380, 190, 420, 230]);
add_block("simulink/Sources/Clock", model + "/Time", ...
    "Position", [30, 310, 70, 340]);
add_block("simulink/Signal Routing/Mux", model + "/Controller input", ...
    "Inputs", "4", "DisplayOption", "bar", ...
    "Position", [455, 105, 465, 300]);
add_chart(model + "/NMPC Lyapunov", [510, 180, 690, 230], [ ...
    "function output = control(value)", ...
    "coder.extrinsic('simulation.simulinkNmpcStep');", ...
    "output = zeros(12,1);", ...
    "output = simulation.simulinkNmpcStep(value);", ...
    "end"]);
add_block("simulink/Signal Routing/Demux", model + "/Controller outputs", ...
    "Outputs", "[3 9]", "Position", [735, 170, 740, 245]);
add_subsystem_plant(model + "/Mecanum plant", initialState, config.dt);
