function reference = read_reference(path, dt)
if ~isfile(path)
    error("build_model:missingReference", "Reference is missing: %s", path);
end
raw = readmatrix(path, "NumHeaderLines", 1);
if size(raw, 2) ~= 7 || size(raw, 1) < 2 || any(~isfinite(raw), "all")
    error("build_model:invalidReference", "Reference needs seven columns");
end
if any(diff(raw(:, 1)) <= 0)
    error("build_model:time", "Reference time must increase");
end
if abs(raw(1, 1)) > 1.0e-12
    raw(:, 1) = raw(:, 1) - raw(1, 1);
end
if any(abs(diff(raw(:, 1)) - dt) > 1.0e-8)
    error("build_model:sample", "Reference sample time must equal dt");
end
reference = raw;
end

function [packed, width] = pack_reference(reference, config)
horizon = config.horizon;
width = 6 * (horizon + 1) + 3 * horizon;
packed = zeros(size(reference, 1), width + 1);
for row = 1:size(reference, 1)
    indices = min(row:(row + horizon), size(reference, 1));
    states = reference(indices, 2:7)';
    alpha = min(1, config.dt / config.velocityTimeConstant);
    currentVelocity = reference(indices(1:end - 1), 5:7)';
    nextVelocity = reference(indices(2:end), 5:7)';
    commands = currentVelocity + (nextVelocity - currentVelocity) / alpha;
    packed(row, :) = [reference(row, 1), states(:)', commands(:)'];
end
end
